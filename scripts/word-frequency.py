"""
Writes src/packs/nl/frequency.ts: how common each core word is in Dutch,
as a Zipf value (7 = extremely common like 'de', 3 = rare), from the
wordfreq dataset (subtitles, Wikipedia, news, web text).

  pip install wordfreq
  npx vitest run ... (dump the core list one word per line), then:
  python3 scripts/word-frequency.py core.txt > src/packs/nl/frequency.ts
"""
import sys
from wordfreq import zipf_frequency

words = [w.strip() for w in open(sys.argv[1], encoding="utf-8") if w.strip()]
print("/**")
print(" * How common each A1 core word is in everyday Dutch (Zipf scale: 7 = 'de',")
print(" * 5 = 'huis', 3 = 'gracht'). Generated by scripts/word-frequency.py from the")
print(" * wordfreq dataset; New words shows the most common words first.")
print(" */")
print("export const zipfA1: Record<string, number> = {")
for w in sorted(words, key=lambda w: -zipf_frequency(w, "nl")):
    key = w if w.isidentifier() else f'"{w}"'
    print(f"  {key}: {zipf_frequency(w, 'nl')},")
print("};")
